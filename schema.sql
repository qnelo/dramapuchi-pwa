-- Schema for Cloudflare D1: DramaPuchi user saves
CREATE TABLE IF NOT EXISTS user_saves (
  sub TEXT PRIMARY KEY,
  email TEXT,
  state TEXT NOT NULL,
  rev INTEGER NOT NULL DEFAULT 1,
  updated_at INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_user_saves_updated ON user_saves(updated_at);

-- Schema for verified Ko-fi donations
CREATE TABLE IF NOT EXISTS donations (
  id TEXT PRIMARY KEY,             -- kofi_transaction_id (unique)
  email TEXT,                      -- donor email
  amount TEXT,                     -- e.g. "1.00", "5.00"
  currency TEXT,                   -- USD
  from_name TEXT,                  -- donor name
  message TEXT,                    -- raw message
  donor_code TEXT,                 -- extracted #DP-XXXX code if any
  claimed_by_sub TEXT,             -- user sub who claimed it
  claimed INTEGER DEFAULT 0,       -- 0 = available, 1 = claimed
  created_at INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_donations_code ON donations(donor_code);
CREATE INDEX IF NOT EXISTS idx_donations_email ON donations(email);

-- Active donor codes generated by players
CREATE TABLE IF NOT EXISTS donor_codes (
  code TEXT PRIMARY KEY,           -- #DP-XXXX
  sub TEXT,                        -- user sub if logged in (nullable)
  created_at INTEGER NOT NULL,
  redeemed INTEGER DEFAULT 0
);

